# ============================================================================== data access (all cached, read-only)
def _read_json(p: Path):
    try:
        return json.loads(p.read_text())
    except (FileNotFoundError, json.JSONDecodeError):
        return None


def _read_csv(p: Path):
    try:
        return pd.read_csv(p)
    except (FileNotFoundError, pd.errors.EmptyDataError):
        return None


# Cached loaders take the repository root as an argument: cache keys must include it, otherwise two copies of this
# app (e.g. in tests) with identical code would share each other's cached files.
@st.cache_data
def _available_runs(root: str) -> list[str]:
    found = {p.parent.name for p in (Path(root) / "reports" / "runs").glob("*/metrics.json")}
    return [r for r in RUN_ORDER if r in found] + sorted(found - set(RUN_ORDER))


def available_runs() -> list[str]:
    return _available_runs(str(ROOT))


@st.cache_data
def _run_config(root: str, run: str) -> dict:
    return _read_json(Path(root) / "reports" / "runs" / run / "config_used.json") or {}


def run_config(run: str) -> dict:
    return _run_config(str(ROOT), run)


def is_simulated(run: str) -> bool:
    return bool(run_config(run).get("simulated"))


def run_label(run: str) -> str:
    if is_simulated(run):
        return f"{run} · SIMULATED demo"
    return f"{run} · {RUN_INFO.get(run, ('local run', ''))[0]}"


def run_kind(run: str) -> tuple[str, str]:
    """(chip text, chip kind) describing where a run's results come from."""
    if is_simulated(run):
        return "SIMULATED demo run · synthetic data", "sim"
    if run in ("reproduce", "reproduce_smoke") or run not in RUN_INFO:
        return f"Results: generated on this machine · reports/runs/{run}", "local"
    return f"Results: committed report · reports/runs/{run}", "report"


def load_run(run: str) -> dict:
    return _load_run(str(ROOT), run)


@st.cache_data
def _load_run(root: str, run: str) -> dict:
    d = Path(root) / "reports" / "runs" / run
    summary = _read_json(d / "training_summary.json") or {"channels": []}
    return {"metrics": _read_json(d / "metrics.json") or {}, "summary": summary, "config": run_config(run),
            "channels": {c["chan_id"]: c for c in summary["channels"]},
            "comparison": _read_csv(d / "comparison.csv"),
            "comparison_calibratable": _read_csv(d / "comparison_calibratable.csv"),
            "per_channel": _read_csv(d / "per_channel.csv"), "events": _read_csv(d / "events.csv"),
            "false_alarms": _read_csv(d / "false_alarms.csv"), "sensitivity": _read_csv(d / "sensitivity.csv"),
            "calibration": _read_json(d / "calibration" / "calibration.json")}


def dataset_info(run: str) -> dict | None:
    """Per-channel metadata. NASA runs: the committed validation report. Demo: its own report (never NASA's)."""
    return _cached_json(str(RUNS_DIR / run / "data_validation.json" if is_simulated(run)
                            else REPORTS / "data_validation.json"))


def seed_summary() -> dict | None:
    return _cached_json(str(REPORTS / "seed_summary.json"))


@st.cache_data
def _cached_json(path: str):
    return _read_json(Path(path))


def raw_dir_for(run: str) -> Path:
    raw = Path(run_config(run).get("data", {}).get("raw_dir", "data/raw/telemanom"))
    return raw if raw.is_absolute() else ROOT / raw


def raw_status(raw_dir: Path) -> dict:
    n_train = len(list((raw_dir / "train").glob("*.npy"))) if (raw_dir / "train").exists() else 0
    n_test = len(list((raw_dir / "test").glob("*.npy"))) if (raw_dir / "test").exists() else 0
    labels = (raw_dir / "labeled_anomalies.csv").exists()
    return {"n_train": n_train, "n_test": n_test, "labels": labels, "ready": labels and n_train > 0 and n_test > 0}


