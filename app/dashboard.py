from src.models.persistence import CHANNEL_ID, METHODS, load_bundle  # noqa: E402
from src.models.thresholds import runs  # noqa: E402

RUN_CONFIGS = {"full": "configs/default.yaml", "smoke": "configs/smoke.yaml",
               "full_seed1": "configs/seed1.yaml", "full_seed2": "configs/seed2.yaml"}
RUNS_DIR, MODELS_DIR = ROOT / "reports" / "runs", ROOT / "models"
SIM_LABEL = "SIMULATED DEMO — NOT NASA BENCHMARK RESULTS"
SIM_TEXT = (f"**{SIM_LABEL}.** Everything on this page comes from synthetic telemetry with hand-made anomalies, "
            "generated by `python -m src.cli demo` to show how the pipeline works. It says nothing about performance "
            "on the NASA SMAP/MSL benchmark or on real spacecraft. Pick a non-demo run in the sidebar for real results.")
