def main():
    st.sidebar.title("Telemetry anomaly detection")
    st.sidebar.caption("NASA SMAP/MSL benchmark (Telemanom) - historical analysis")
    runs_ = available_runs()
    if st.sidebar.button("Reload run data", help="Clear cached files after re-running the pipeline or the demo"):
        st.cache_data.clear()
        runs_ = available_runs()
    if not runs_:
        st.sidebar.info("No evaluated runs yet.")
        page_start(None, [])
        return
    default = "full" if "full" in runs_ else runs_[0]
    run = st.sidebar.selectbox("Experiment run", runs_, index=runs_.index(default), format_func=run_label)
    if is_simulated(run):
        st.sidebar.error(f"{SIM_LABEL}. Synthetic data generated by `python -m src.cli demo`.")
    elif run == "smoke":
        st.sidebar.warning("Smoke run: tiny model, 3 channels - metrics are not meaningful.")
    page = st.sidebar.radio("Page", PAGES)
    if is_simulated(run):
        st.error(SIM_TEXT)                       # persistent banner on EVERY page of a simulated run
    if page == "Start here":
        page_start(run, runs_)
    else:
        rd = load_run(run)
        {"Overview": page_overview, "Telemetry explorer": page_explorer, "Anomaly analysis": page_anomalies,
         "Model comparison": page_comparison, "Inference": page_inference}[page](run, rd)
    st.sidebar.markdown("---")
    st.sidebar.caption(DISCLAIMER)


main()
