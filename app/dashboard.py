@st.fragment(run_every="5s")
def job_panel():
    from src.jobs import EXPECTED_CHANNELS, job_status

    shown = False
    for run in ("reproduce_smoke", "reproduce"):
        js = job_status(ROOT, run)
        if js["state"] == "none":
            continue
        shown = True
        total = max(js["total"] or EXPECTED_CHANNELS[run], 1)
        label = {"running": "running", "finished": "finished", "failed": "failed", "stopped":
                 "stopped (start again to resume)"}[js["state"]]
        st.progress(min(js["done"] / total, 1.0), text=f"{run} · {label} · {js['done']}/{total} channels")
        if js["state"] == "failed" and js["log_tail"]:
            st.code(js["log_tail"], language="text")
        if js["state"] == "finished":
            def _load(r=run):
                st.cache_data.clear()
                st.session_state.update(run=r, page="Overview")
            if st.button(f"Load results of {run}", key=f"load_{run}", on_click=_load):
                st.rerun(scope="app")
    if not shown:
        st.caption("No local reproduction started yet.")


def page_inference(run: str, rd: dict, mission: str):
    sim = is_simulated(run)
    st.markdown("# Inference with a saved model")
    st.markdown("Score a telemetry sequence with a detector saved during training. The saved scaler and threshold are "
                "reused, never refitted. " + DISCLAIMER)
    if not has_models(run):
        with_models = [r for r in available_runs() if has_models(r) and (not is_simulated(r) or sim)]
        st.markdown(T.chips((f"Saved models: not generated for run {run}", "missing")), unsafe_allow_html=True)
        st.markdown(T.step(None, "Saved models are created by training on this machine",
                           "They are not stored in the repository (~190 MB for 81 channels). Use <b>Data &amp; "
                           "reproducibility</b> → quick check (~30 s) or full reproduction (~1–2 h), or run "
                           f"<code>python -m src.cli all --config {RUN_INFO.get(run, ('', 'configs/&lt;run&gt;.yaml'))[1]} "
                           "--resume</code>."), unsafe_allow_html=True)
        if with_models:
            st.info(f"Runs with saved models on this machine: {', '.join(with_models)}. Select one in the sidebar.")
        go_to("Data & reproducibility", "Go to reproduction", key="inference")
        return
    run_models = MODELS_DIR / run
    chans = [c for c in sorted((p.name for p in (run_models / "lstm").glob("*") if CHANNEL_ID.fullmatch(p.name)),
                               key=chan_key)
             if mission == "All" or rd["channels"].get(c, {}).get("spacecraft") == mission]
    if not chans:
        st.info("No saved models for this mission in this run.")
        return
    raw = raw_dir_for(run)
    sample = RUNS_DIR / run / "sample_input.csv"
    c1, c2, c3 = st.columns(3)
    chan = c1.selectbox("Channel model", chans, key="inf_chan")
    method = c2.selectbox("Method", METHODS, format_func=LABELS.get, key="inf_method")
    options = (["Demo sample input (synthetic)"] if sim and sample.exists() else []) + \
              (["Demo test file (synthetic)" if sim else "Benchmark test file (downloaded NASA data)"]
               if raw_status(raw)["ready"] else []) + ["Upload CSV"]
    source = c3.radio("Input", options, key="inf_src")
    try:
        bundle = load_bundle(run_models, method, chan)
    except FileNotFoundError:
        st.info(f"No saved {LABELS[method]} model for {chan} in run `{run}`.")
        return
    st.markdown(T.chips((f"Model: local artifact · models/{run}/{method}/{chan}", "local"),
                        ("SIMULATED demo", "sim") if sim else ("NASA benchmark channel", "hist")), unsafe_allow_html=True)
    if bundle.calibration_warning():
        st.warning(bundle.calibration_warning())
    st.caption(f"Expects a `value` column plus optional `cmd_0..cmd_{bundle.n_features - 2}` (0/1). Needs more than "
               f"{warmup_length(bundle)} rows. Values in the benchmark's scaled units.")
    df = None
    if source == "Upload CSV":
        up = st.file_uploader("Telemetry CSV", type="csv")
        tmpl = pd.DataFrame({"value": [0.0] * 3, **{f"cmd_{i}": [0] * 3 for i in range(bundle.n_features - 1)}})
        st.download_button("Download CSV template", tmpl.to_csv(index=False), "telemetry_template.csv")
        if up is not None:
            try:
                df = read_telemetry_csv(up)
            except (pd.errors.ParserError, UnicodeDecodeError, ValueError) as exc:
                st.error(f"Could not read CSV: {exc}")
    elif source.startswith("Demo sample"):
        st.warning(f"{SIM_LABEL}: new synthetic sequence for model Z-1 with 2 injected anomalies.")
        df = read_telemetry_csv(sample)
    else:
        arr = load_channel(raw, chan, "test")
        df = pd.DataFrame(arr, columns=["value"] + [f"cmd_{i}" for i in range(arr.shape[1] - 1)])
    if df is None:
        st.caption("Choose an input to score.")
        return
    try:
        arr, warns = frame_to_array(df, bundle.n_features)
        for w in warns:
            st.warning(w)
        with st.spinner("Scoring…"):
            out = detect(bundle, arr)
    except ValueError as exc:
        st.error(f"Invalid input: {exc}")
        return
    c = st.columns(3)
    c[0].metric("Samples scored", f"{int(out['scored'].sum()):,}")
    c[1].metric("Flagged as anomalous", f"{int(out['is_anomaly'].sum()):,}")
    c[2].metric("Threshold", f"{bundle.threshold:.4g}")
    st.plotly_chart(channel_figure(out["value"].to_numpy(), [], runs_of(out["is_anomaly"].to_numpy()),
                                   out["score"].to_numpy(), bundle.threshold, method, f"{chan} · scored input",
                                   sim=sim), width="stretch", config=T.PLOT_CONFIG)
    st.dataframe(out[out["is_anomaly"] == 1].head(500), width="stretch", height=240)
    st.download_button("Download scored CSV", out.to_csv(index=False), f"{chan}_{method}_scores.csv")


