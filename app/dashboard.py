def n_scores(run: str) -> int:
    d = RUNS_DIR / run / "scores"
    return len(list(d.glob("*.parquet"))) - len(list(d.glob("*.val.parquet"))) if d.exists() else 0


def has_models(run: str) -> bool:
    d = MODELS_DIR / run / "lstm"
    return d.exists() and any(CHANNEL_ID.fullmatch(p.name) for p in d.glob("*"))


def chan_key(c: str):
    letter, _, num = c.partition("-")
    return (letter, int(num) if num.isdigit() else 0)


def channels_for(run: str, mission: str) -> list[str]:
    info = dataset_info(run) or {}
    chans = info.get("channels") or {c: {"spacecraft": v.get("spacecraft")} for c, v in load_run(run)["channels"].items()}
    return sorted([c for c, v in chans.items() if mission == "All" or v.get("spacecraft") == mission], key=chan_key)


def channel_events(rd: dict, chan: str) -> pd.DataFrame:
    ev = rd["events"]
    if ev is None:
        return pd.DataFrame(columns=["start", "end", "length", "class"])
    first = ev[ev.chan_id == chan]
    return first.drop_duplicates(["start", "end"])[["start", "end", "length", "class"]].reset_index(drop=True)


def table(df: pd.DataFrame, fmt: dict, **kw):
    """st.dataframe with Streamlit-native number formats (pandas Styler formats are not applied by st.dataframe)."""
    cfg = {c: st.column_config.NumberColumn(format=f) for c, f in fmt.items() if c in df.columns}
    st.dataframe(df, width="stretch", column_config=cfg, **kw)


def fit_height(n_rows: int) -> int:
    """Pixel height that shows every row of a st.dataframe without an inner scrollbar."""
    return 38 + 35 * n_rows


def fmt_pct(x) -> str:
    return "—" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.1%}"


# ============================================================================== chart helpers
def add_bands(fig, intervals, color: str, name: str, row=None, opacity=0.22, limit: int = 120, y_level: float = 0.0):
    """Shade [start, end] intervals. Many intervals are drawn as one marker trace (at ``y_level``, which must be
    visible on the axis, e.g. the threshold on a log-scaled score axis) to keep the browser fast."""
    intervals = list(intervals)
    if not intervals:
        return
    kw = {"row": row, "col": 1} if row else {}
    if len(intervals) <= limit:
        for i, (s, e) in enumerate(intervals):
            # label only the first band: annotation_text=None would make plotly draw a default "new text" label
            label = {"annotation_text": name, "annotation_position": "top left",
                     "annotation_font_color": T.TEXT} if i == 0 else {}
            fig.add_vrect(x0=s - 0.5, x1=e + 0.5, fillcolor=color, opacity=opacity, line=dict(color=color, width=1),
                          layer="below", **label, **kw)
    else:
        xs = np.concatenate([np.arange(s, e + 1) for s, e in intervals])
        fig.add_trace(go.Scattergl(x=xs, y=np.full(len(xs), y_level), mode="markers", marker=dict(color=color, size=4,
                                   symbol="line-ns-open"), name=f"{name} ({len(intervals)} runs)",
                                   hovertemplate="sample %{x}<extra></extra>"), **kw)


def channel_figure(values: np.ndarray, label_iv, pred_iv=None, score=None, thr=None, method=None,
                   title: str = "", x_range=None, sim: bool = False) -> go.Figure:
    rows = 2 if score is not None else 1
    fig = make_subplots(rows=rows, cols=1, shared_xaxes=True, vertical_spacing=0.06,
                        row_heights=[0.55, 0.45] if rows == 2 else [1.0])
    x = np.arange(len(values))
    fig.add_trace(go.Scattergl(x=x, y=values, mode="lines", name="telemetry value", opacity=0.8,
                               line=dict(color=T.TRACE, width=0.9),
                               hovertemplate="sample %{x}<br>value %{y:.4f}<extra></extra>"), row=1, col=1)
    add_bands(fig, label_iv, T.LABEL, "labelled anomaly", row=1, opacity=0.35)
    if pred_iv is not None and method:
        level = thr if (score is not None and thr) else float(np.nanmin(values))
        add_bands(fig, pred_iv, COLORS[method], f"{LABELS[method]} flag", row=rows, opacity=0.35, y_level=level)
    if score is not None:
        fig.add_trace(go.Scattergl(x=x, y=score, mode="lines", name=f"{LABELS[method]} score",
                                   line=dict(color=COLORS[method], width=1.1),
                                   hovertemplate="sample %{x}<br>score %{y:.4g}<extra></extra>"), row=2, col=1)
        if thr is not None:
            fig.add_hline(y=thr, line=dict(color=T.THRESH, dash="dash", width=1.4), row=2, col=1,
                          annotation_text=f"threshold {thr:.3g}", annotation_font_color=T.THRESH)
        fig.update_yaxes(title_text="score (log)", type="log", row=2, col=1)
    fig.update_yaxes(title_text="value (benchmark-scaled)", row=1, col=1)
    fig.update_xaxes(title_text="sample index (no timestamps in the benchmark)", row=rows, col=1)
    fig.update_layout(title=("[SIMULATED DEMO] " if sim else "") + title, height=470 if rows == 2 else 330,
                      hovermode="x unified")
    if x_range:
        fig.update_xaxes(range=x_range)
    return fig


def methods_in(rd: dict) -> list[str]:
    comp = rd["comparison"]
    return [m for m in METHODS if comp is not None and m in set(comp["method"])]


def go_to(page: str, label: str | None = None, key: str = ""):
    """Button that switches the sidebar navigation (no dead-end empty states)."""
    st.button(label or f"Open {page}", key=f"goto_{page}_{key}",
              on_click=lambda: st.session_state.update(page=page))


def no_report(what: str, run: str):
    st.info(f"No {what} in `reports/runs/{run}/` for this run. Committed NASA runs (`full`, `full_seed1`, "
            "`full_seed2`) include it; a local run creates it when its evaluation finishes.")


# ============================================================================== sidebar
def sidebar() -> tuple[str, str | None, str]:
    sb = st.sidebar
    sb.markdown('<div class="lab-brand">Telemetry Anomaly <span>Lab</span></div>'
                '<div class="muted">NASA SMAP &amp; MSL · historical benchmark</div>', unsafe_allow_html=True)
    page = sb.radio("Navigate", PAGES, key="page")
    show_demo = bool(st.session_state.get("show_demo", False))
    runs_all = available_runs()
    runs_ = [r for r in runs_all if not is_simulated(r) or show_demo]
    run = None
    if runs_:
        default = "full" if "full" in runs_ else runs_[0]
        run = sb.selectbox("Results run", runs_, index=runs_.index(default), format_func=run_label, key="run",
                           help="`full` is the headline run (seed 42). Seeds 1 and 2 measure seed variance.")
    mission = sb.radio("Mission", ["All", "SMAP", "MSL"], horizontal=True, key="mission",
                       help="SMAP = Soil Moisture Active Passive satellite; MSL = Mars Science Laboratory "
                            "(Curiosity rover). Filters channels, events and per-mission metrics.")
    if sb.button("Refresh from disk", help="Re-read reports and files after downloading data or finishing a run"):
        st.cache_data.clear()
        st.rerun()
    with sb.expander("Optional: synthetic demo"):
        st.markdown("A 30-second **synthetic** run (`python -m src.cli demo`) for trying the pipeline without "
                    "NASA data. It is not NASA data and is hidden by default.")
        st.toggle("Show the synthetic demo run", key="show_demo",
                  disabled=not any(is_simulated(r) for r in runs_all),
                  help="Available after running `python -m src.cli demo`.")
    sb.markdown("---")
    sb.caption(DISCLAIMER)
    return page, run, mission


