def page_events(run: str, rd: dict, mission: str):
    st.markdown("# Events & errors")
    ev, fa = rd["events"], rd["false_alarms"]
    if ev is None:
        no_report("event analysis", run)
        return
    st.markdown(T.chips(("Source: committed report · events.csv, false_alarms.csv", "report")
                        if not is_simulated(run) else ("SIMULATED demo events", "sim")), unsafe_allow_html=True)
    if mission != "All":
        ev = ev[ev.spacecraft == mission]
        fa = fa[fa.spacecraft == mission] if fa is not None else None
    methods = [m for m in METHODS if m in set(ev.method)]
    if not methods:
        st.info("No events for this mission in this run.")
        return
    rows = []
    for m in methods:
        e = ev[ev.method == m]
        n_fa = int((fa.method == m).sum()) if fa is not None else 0
        det = int(e.detected.sum())
        rows.append({"Method": LABELS[m], "Detected": f"{det}/{len(e)}", "Event recall": 100 * det / max(len(e), 1),
                     "False-alarm events": n_fa, "Event precision": 100 * det / max(det + n_fa, 1),
                     "Median latency (samples)": e.loc[e.detected, "latency"].median()})
    t = pd.DataFrame(rows).set_index("Method")
    table(t, {"Event recall": "%.1f%%", "Event precision": "%.1f%%", "False-alarm events": "localized",
              "Median latency (samples)": "%.0f"})
    st.caption("Latency = samples from the labelled start to the first flagged sample. A false-alarm event is a "
               "flagged run that overlaps no labelled interval.")
    c1, c2 = st.columns(2)
    with c1:
        fig = go.Figure()
        for m in methods:
            e = ev[ev.method == m].groupby("class")["detected"].mean()
            fig.add_bar(name=LABELS[m], x=list(e.index), y=list(e.values), marker_color=COLORS[m],
                        marker_pattern_shape=T.METHOD_PATTERNS[m])
        fig.update_layout(barmode="group", height=330, yaxis=dict(range=[0, 1], title="event recall"),
                          title="Detection by anomaly class")
        st.plotly_chart(fig, width="stretch", config=T.PLOT_CONFIG)
    with c2:
        if fa is not None and len(fa):
            mm = st.selectbox("False alarms for", methods, index=len(methods) - 1, format_func=LABELS.get, key="fa_m")
            top = fa[fa.method == mm].chan_id.value_counts().head(12)[::-1]
            fig = go.Figure(go.Bar(x=top.values, y=top.index, orientation="h", marker_color=COLORS[mm],
                                   hovertemplate="%{y}: %{x} false-alarm events<extra></extra>"))
            fig.update_layout(height=290, title="Most false-alarm events", xaxis_title="false-alarm events by channel")
            st.plotly_chart(fig, width="stretch", config=T.PLOT_CONFIG)
    st.markdown("## Event browser")
    f1, f2, f3 = st.columns(3)
    cls = f1.selectbox("Class", ["All"] + sorted(ev["class"].dropna().unique()), key="eb_cls")
    mo = f2.selectbox("Outcome for", methods, index=len(methods) - 1, format_func=LABELS.get, key="eb_m")
    out = f3.selectbox("Outcome", ["All", "Detected", "Missed"], key="eb_out")
    e = ev[ev.method == mo]
    if cls != "All":
        e = e[e["class"] == cls]
    if out != "All":
        e = e[e.detected == (out == "Detected")]
    e = e.assign(_k=e.chan_id.map(chan_key)).sort_values(["_k", "start"]).drop(columns="_k")
    st.dataframe(e[["chan_id", "spacecraft", "start", "end", "length", "class", "detected", "latency",
                    "peak_norm_score"]], width="stretch", hide_index=True, height=260)
    st.caption("peak_norm_score = highest score / threshold inside the labelled window (< 1: never crossed).")
    if not len(e):
        return
    pick = st.selectbox("Inspect event", list(e.index), key="eb_pick",
                        format_func=lambda i: f"{e.loc[i, 'chan_id']} · samples {e.loc[i, 'start']}–{e.loc[i, 'end']} "
                                              f"· {e.loc[i, 'class']} · {'detected' if e.loc[i, 'detected'] else 'missed'}")
    row = e.loc[pick]
    raw = raw_dir_for(run)
    values = load_raw(str(raw), row.chan_id, "test") if raw_status(raw)["ready"] else None
    if values is None:
        st.markdown(T.step(None, "Download the NASA telemetry to see this event in context",
                           "~170 MB, 1–5 min, or <code>python -m src.cli download</code>."), unsafe_allow_html=True)
        go_to("Data & reproducibility", "Go to download", key="events")
        return
    scores = load_scores(run, row.chan_id)
    pad = max(150, int(row.length))
    xr = [max(0, int(row.start) - pad), min(len(values) - 1, int(row.end) + pad)]
    lab = channel_events(rd, row.chan_id)
    score = scores[f"{mo}_score"].to_numpy() if scores is not None else None
    pred = runs_of(scores[f"{mo}_pred"].to_numpy()) if scores is not None else None
    thr = rd["channels"].get(row.chan_id, {}).get("methods", {}).get(mo, {}).get("threshold")
    st.plotly_chart(channel_figure(values, lab[["start", "end"]].itertuples(index=False), pred, score,
                                   thr if score is not None else None, mo if score is not None else None,
                                   f"{row.chan_id} · event at samples {row.start}–{row.end}", xr, is_simulated(run)),
                    width="stretch", config=T.PLOT_CONFIG)
    if scores is None:
        st.caption("Telemetry and labels shown; model scores appear here once this run's scores are generated locally.")


def page_models(run: str, rd: dict, mission: str):
    st.markdown("# Models & calibration")
    comp, compc = rd["comparison"], rd["comparison_calibratable"]
    if comp is None:
        no_report("comparison", run)
        return
    st.markdown(T.chips(("Source: committed reports · comparison*.csv, calibration/, seed_summary.json", "report")
                        if not is_simulated(run) else ("SIMULATED demo", "sim")), unsafe_allow_html=True)
    st.markdown("## All channels vs calibratable channels")
    names = {"precision": "Precision", "recall": "Recall", "f1": "F1", "event_recall": "Event recall",
             "event_f1": "Event F1", "event_fp": "False-alarm events", "roc_auc_macro": "ROC-AUC (macro)",
             "pr_auc_macro": "PR-AUC (macro)"}
    parts = []
    for df, label in ((comp, "all"), (compc, "calibratable")):
        if df is not None and len(df):
            d = df[["method", *names]].rename(columns=names)
            d.insert(1, "Channels", f"{label} ({int(df['n_channels'].iloc[0])})")
            d["method"] = d["method"].map(LABELS)
            parts.append(d.rename(columns={"method": "Method"}))
    both = pd.concat(parts).sort_values(["Method", "Channels"], kind="stable")
    table(both, {c: "%.3f" for c in names.values() if c != "False-alarm events"} | {"False-alarm events": "localized"},
          hide_index=True, height=fit_height(len(both)))
    st.caption("Calibratable channels exclude those whose training signal is constant or whose validation scores "
               "have no spread (threshold ≈ 0, any change flagged).")
    seeds = seed_summary()
    if seeds and not is_simulated(run):
        st.markdown("## Seed variability (seeds 42, 1, 2)")
        pr = pd.DataFrame(seeds["per_run"])
        pr = pr[pr.subset == "overall"]
        metric = st.selectbox("Metric", ["f1", "event_f1", "event_fp", "roc_auc_macro", "pr_auc_macro", "precision",
                                         "recall"], key="seed_metric")
        fig = go.Figure()
        for m in METHODS:
            d = pr[pr.method == m]
            fig.add_trace(go.Scatter(x=[LABELS[m]] * len(d), y=d[metric], mode="markers", name=LABELS[m],
                                     marker=dict(color=COLORS[m], size=11, symbol=T.METHOD_SYMBOLS[m],
                                                 line=dict(color=T.BG, width=1)),
                                     text=[f"seed {s}" for s in d.seed],
                                     hovertemplate="%{text}: %{y:.4g}<extra>" + LABELS[m] + "</extra>"))
        fig.update_layout(height=300, showlegend=False, yaxis_title=metric)
        st.plotly_chart(fig, width="stretch", config=T.PLOT_CONFIG)
        st.caption("The baseline has no randomness (identical across seeds). The headline seed 42 is the most "
                   "favourable of the three on event F1 and false alarms.")
    cal = rd["calibration"]
    if cal:
        st.markdown("## Leave-channels-out calibration (an estimate for unseen channels)")
        st.caption("A threshold rule is chosen on four folds of channels by event F1 and applied to the held-out "
                   "fold; the held-out channels' labels never influence their rule. The headline results stay at the "
                   "a-priori default. Caveat: the chosen rules sit at the edge of the pre-specified grid.")
        rows = []
        for m in METHODS:
            if m not in cal["leave_channels_out"]:
                continue
            for sub in ("all", "calibratable"):
                for name, lbl in (("default", "default 99.5% rule"), ("lco", "leave-channels-out rule")):
                    r = cal["leave_channels_out"][m][sub][name]
                    rows.append({"Method": LABELS[m], "Channels": sub, "Rule": lbl, "Precision": r["precision"],
                                 "Recall": r["recall"], "F1": r["f1"], "Event recall": r["event_recall"],
                                 "Event F1": r["event_f1"], "False-alarm events": r["event_fp"]})
        d = pd.DataFrame(rows)
        table(d, {c: "%.3f" for c in ["Precision", "Recall", "F1", "Event recall", "Event F1"]}
              | {"False-alarm events": "localized"}, hide_index=True, height=fit_height(len(d)))
        st.markdown("## Threshold-estimation noise (block bootstrap)")
        u = cal["uncertainty"]
        st.dataframe(pd.DataFrame([{"Method": LABELS[m], **{lab: f"{u[m]['point_estimate'][k]:.3f} "
                                                            f"[{u[m]['interval_90'][k][0]:.3f}, {u[m]['interval_90'][k][1]:.3f}]"
                                                            for k, lab in (("precision", "Precision"), ("recall", "Recall"),
                                                                           ("f1", "F1"), ("event_f1", "Event F1"))}}
                                   for m in METHODS if m in u]), width="stretch", hide_index=True)
        st.caption("Point estimate [5th, 95th percentile] over 100 resamples of each channel's validation scores. "
                   "Biased toward lower thresholds (a resampled quantile cannot exceed the sample maximum): read as "
                   "the size of the noise, not a confidence interval.")
    pc = rd["per_channel"]
    if pc is not None:
        st.markdown("## Precision vs recall per channel")
        d = pc if mission == "All" else pc[pc.spacecraft == mission]
        fig = go.Figure()
        for m in METHODS:
            x = d[d.method == m]
            fig.add_trace(go.Scatter(x=x.recall, y=x.precision, mode="markers", name=LABELS[m],
                                     marker=dict(color=COLORS[m], size=8, opacity=0.8, symbol=T.METHOD_SYMBOLS[m]),
                                     text=x.chan_id,
                                     hovertemplate="%{text}<br>recall %{x:.3f} · precision %{y:.3f}<extra></extra>"))
        fig.update_layout(height=380, xaxis=dict(title="point recall", range=[-0.02, 1.02]),
                          yaxis=dict(title="point precision", range=[-0.02, 1.02]))
        st.plotly_chart(fig, width="stretch", config=T.PLOT_CONFIG)
    sens = rd["sensitivity"]
    if sens is not None:
        with st.expander("Post-hoc threshold sensitivity (diagnostic only: computed with test labels, not used to choose anything)"):
            if "scale_comparable" in sens:
                sens = sens[sens["scale_comparable"]]
            fig = go.Figure([go.Scatter(x=sens[sens.method == m]["point_recall"], y=sens[sens.method == m]["point_precision"],
                                        mode="lines+markers+text", text=sens[sens.method == m]["multiplier"],
                                        textposition="top center", name=LABELS[m], line_color=COLORS[m])
                             for m in sens["method"].unique()])
            fig.update_layout(xaxis_title="point recall", yaxis_title="point precision", height=340)
            st.plotly_chart(fig, width="stretch", config=T.PLOT_CONFIG)
            st.caption("Each point multiplies every calibrated threshold by k (label). Isolation Forest is omitted: "
                       "its bounded score scale makes multipliers meaningless.")


