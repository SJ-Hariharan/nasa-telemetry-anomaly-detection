"""Streamlit dashboard for the historical NASA SMAP/MSL telemetry anomaly-detection experiments.

Launch:  streamlit run app/dashboard.py

The dashboard never trains anything. It reads
  reports/data_validation.json            NASA dataset summary (real runs)
  reports/runs/<run>/...                  scores, metrics, error analysis (from `src.cli all` or `src.cli demo`)
  models/<run>/<method>/<chan>/           saved detectors (Inference page)
  <run's data.raw_dir>                    raw telemetry for context plots (NASA data, or the synthetic demo data)

Runs whose config_used.json has "simulated": true (the `demo` run) are labelled SIMULATED on every page and their
data is read only from their own folder, so demo numbers are never shown as NASA results.
"""
